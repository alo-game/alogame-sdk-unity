#if UNITY_ANDROID
using System;
using System.IO;
using System.Security;
using System.Text;
using UnityEditor;
using UnityEditor.Android;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEngine;

namespace Alogame.SDK.Editor
{
    /// <summary>
    /// Turns Assets/**/google-services.json into the string resources Firebase reads at startup
    /// (what the com.google.gms.google-services Gradle plugin generates), so FCM push and
    /// Firebase Analytics work without the game editing Gradle templates. Skipped when the
    /// Firebase Unity SDK is in the project — it generates the same resources and two copies
    /// fail the build with "Duplicate resources".
    ///
    /// Also fails the build early when minSdk is below the native SDK's 24, instead of a
    /// manifest-merger error deep in the Gradle log.
    /// </summary>
    public sealed class AlogameAndroidGoogleServices : IPostGenerateGradleAndroidProject, IPreprocessBuildWithReport
    {
        private const string Tag = "[Alogame SDK]";
        private const int MinSdk = 24;
        private const string ResourceFile = "alogame_google_services.xml";

        public int callbackOrder => 101;

        public void OnPreprocessBuild(BuildReport report)
        {
            if (report.summary.platform != BuildTarget.Android) return;
            if ((int)PlayerSettings.Android.minSdkVersion < MinSdk)
                throw new BuildFailedException(Tag + " Android minimum API level must be " + MinSdk +
                    " or higher (Player Settings > Other Settings > Minimum API Level). The Alogame SDK requires it.");
        }

        public void OnPostGenerateGradleAndroidProject(string path)
        {
            var valuesDir = Path.Combine(path, "src", "main", "res", "values");
            var target = Path.Combine(valuesDir, ResourceFile);

            if (Directory.Exists(Path.Combine(path, "FirebaseApp.androidlib")) ||
                Directory.GetDirectories(Application.dataPath, "FirebaseApp.androidlib", SearchOption.AllDirectories).Length > 0)
            {
                if (File.Exists(target)) File.Delete(target);
                Debug.Log(Tag + " Firebase Unity SDK present — it provides the google-services resources.");
                return;
            }

            var source = AlogameAssetSearch.FindInAssets("google-services.json");
            if (source == null)
            {
                if (File.Exists(target)) File.Delete(target);
                Debug.LogWarning(Tag + " no google-services.json under Assets — push (FCM) and Firebase Analytics " +
                                 "will not start on Android. Download it from the Firebase console (Android app with " +
                                 "package " + PlayerSettings.applicationIdentifier + ") and put it anywhere under Assets.");
                return;
            }

            GoogleServices json;
            try { json = JsonUtility.FromJson<GoogleServices>(File.ReadAllText(source)); }
            catch (Exception e)
            {
                Debug.LogError(Tag + " could not read " + source + ": " + e.Message);
                return;
            }

            var package = PlayerSettings.applicationIdentifier;
            Client client = null;
            foreach (var c in json?.client ?? Array.Empty<Client>())
            {
                if (c?.client_info?.android_client_info?.package_name == package) { client = c; break; }
            }
            if (client == null)
            {
                Debug.LogError(Tag + " google-services.json has no Android client for package '" + package +
                               "'. Add this package to the Firebase project and download the file again.");
                return;
            }

            var values = new StringBuilder();
            values.Append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by AlogameAndroidGoogleServices from ")
                  .Append(Path.GetFileName(source)).Append(" — do not edit. -->\n<resources>\n");
            void Add(string name, string value)
            {
                if (string.IsNullOrEmpty(value)) return;
                values.Append("    <string name=\"").Append(name).Append("\" translatable=\"false\">")
                      .Append(SecurityElement.Escape(value)).Append("</string>\n");
            }

            Add("google_app_id", client.client_info.mobilesdk_app_id);
            Add("gcm_defaultSenderId", json.project_info?.project_number);
            Add("project_id", json.project_info?.project_id);
            Add("google_storage_bucket", json.project_info?.storage_bucket);
            Add("firebase_database_url", json.project_info?.firebase_url);
            var apiKey = client.api_key != null && client.api_key.Length > 0 ? client.api_key[0].current_key : null;
            Add("google_api_key", apiKey);
            Add("google_crash_reporting_api_key", apiKey);
            foreach (var oauth in client.oauth_client ?? Array.Empty<OAuthClient>())
            {
                if (oauth.client_type == 3) { Add("default_web_client_id", oauth.client_id); break; }
            }
            values.Append("</resources>\n");

            Directory.CreateDirectory(valuesDir);
            File.WriteAllText(target, values.ToString());
            Debug.Log(Tag + " generated Firebase resources from " + source + ".");
        }

        // JsonUtility needs concrete serializable types; only the fields read above.
#pragma warning disable 0649
        [Serializable] private sealed class GoogleServices { public ProjectInfo project_info; public Client[] client; }
        [Serializable] private sealed class ProjectInfo { public string project_number; public string project_id; public string storage_bucket; public string firebase_url; }
        [Serializable] private sealed class Client { public ClientInfo client_info; public OAuthClient[] oauth_client; public ApiKey[] api_key; }
        [Serializable] private sealed class ClientInfo { public string mobilesdk_app_id; public AndroidClientInfo android_client_info; }
        [Serializable] private sealed class AndroidClientInfo { public string package_name; }
        [Serializable] private sealed class OAuthClient { public string client_id; public int client_type; }
        [Serializable] private sealed class ApiKey { public string current_key; }
#pragma warning restore 0649
    }
}
#endif
